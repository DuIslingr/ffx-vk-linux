#!/usr/bin/env python3
"""gen_vk_thunks.py <vk.xml> <out.inc>: a Microsoft x64 (ms_abi) wrapper for every Vulkan command
vulkan_core.h declares (core and the extensions with no platform), forwarding to the real one -
what a Windows DLL gets in place of each Vulkan function it imports or asks vkGetDeviceProcAddr for."""
import sys
import xml.etree.ElementTree as ET

reg = ET.parse(sys.argv[1]).getroot()

# the commands vulkan_core.h has: required by a core feature or a non-platform extension
platform_ext = set()
wanted = set()
for feat in reg.findall("feature"):
    if "vulkan" not in feat.get("api", "vulkan").split(","):
        continue
    for req in feat.findall("require"):
        for c in req.findall("command"):
            wanted.add(c.get("name"))
for ext in reg.find("extensions").findall("extension"):
    if ext.get("platform") or ext.get("supported") in ("disabled",) or "vulkan" not in ext.get("supported", "vulkan").split(","):
        continue
    if ext.get("provisional") == "true":
        continue
    for req in ext.findall("require"):
        if "vulkan" not in req.get("api", "vulkan").split(","):
            continue
        for c in req.findall("command"):
            wanted.add(c.get("name"))

commands = {}
aliases = {}
for cmd in reg.find("commands").findall("command"):
    if "vulkan" not in cmd.get("api", "vulkan").split(","):
        continue
    if cmd.get("alias"):
        aliases[cmd.get("name")] = cmd.get("alias")
        continue
    proto = cmd.find("proto")
    name = proto.find("name").text
    ret = "".join(proto.itertext())[: -len(name)].strip()
    params = []
    for p in cmd.findall("param"):
        if "vulkan" not in p.get("api", "vulkan").split(","):
            continue
        pname = p.find("name").text
        params.append(("".join(p.itertext()).strip(), pname))
    commands[name] = (ret, params)

out = ["// generated by tools/gen_vk_thunks.py from vk.xml - do not edit", ""]
table = []
for name in sorted(wanted):
    target = name
    while target in aliases:
        target = aliases[target]
    if target not in commands:
        continue
    ret, params = commands[target]
    decl = ", ".join(t for t, _ in params) or "void"
    args = ", ".join(n for _, n in params)
    out.append(f"static PFN_{name} r_{name};")
    out.append(f"static __attribute__((ms_abi)) {ret} w_{name}({decl}) {{ return r_{name}({args}); }}")
    table.append(f'    {{"{name}", reinterpret_cast<PFN_vkVoidFunction*>(&r_{name}), reinterpret_cast<PFN_vkVoidFunction>(&w_{name})}},')
out.append("")
out.append("static const VkThunk kThunks[] = {")
out += table
out.append("};")
open(sys.argv[2], "w").write("\n".join(out) + "\n")
print(f"{len(table)} Vulkan thunks")
